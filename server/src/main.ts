import { NestFactory } from '@nestjs/core';
import { ValidationPipe, Logger } from '@nestjs/common';
import { SwaggerModule, DocumentBuilder } from '@nestjs/swagger';
import { ConfigService } from '@nestjs/config';

import { AppModule } from './app.module';

async function bootstrap() {
  const logger = new Logger('Bootstrap');
  const app = await NestFactory.create(AppModule);

  const configService = app.get(ConfigService);
  const port = configService.get<number>('port') || 8000;
  const corsOrigins = configService.get<string[]>('corsOrigin');

  // Global validation pipe
  app.useGlobalPipes(
    new ValidationPipe({
      whitelist: true,
      transform: true,
      forbidNonWhitelisted: false,
      transformOptions: {
        enableImplicitConversion: true,
      },
    }),
  );

  // CORS
  app.enableCors({
    origin: corsOrigins,
    credentials: true,
    methods: ['GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'OPTIONS'],
    allowedHeaders: ['Content-Type', 'Authorization', 'X-Requested-With'],
  });

  // OpenAPI Swagger Documentation
  const config = new DocumentBuilder()
    .setTitle('CIRCUIT Intelligence API')
    .setDescription(
      'CIRCUIT — Criminal Intelligence & Relationship Investigation using Connected-Entity Tracking.\n\n' +
      'Production-grade core backend for criminal network intelligence, document AI, and case workflows.',
    )
    .setVersion('1.0.0')
    .addBearerAuth()
    .build();

  const document = SwaggerModule.createDocument(app, config);
  SwaggerModule.setup('api/docs', app, document);

  await app.listen(port);
  logger.log(`🚀 CIRCUIT Core Backend is running on http://localhost:${port}`);
  logger.log(`📚 Interactive Swagger API Docs available at http://localhost:${port}/api/docs`);
}
bootstrap();
